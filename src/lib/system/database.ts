import type { SupabaseClient } from "@supabase/supabase-js";
import manifest from "./migrations-manifest.json";

/**
 * Database section of the system console (system.zapnivo.com).
 *
 * Everything here is read-only and honest:
 *  - connectivity is a bounded head-count probe (no arbitrary SQL is ever run —
 *    there is deliberately NO query console);
 *  - row counts are exact head counts per table, run in parallel via
 *    Promise.allSettled so one failure never blocks the others;
 *  - a table that errors reports "unavailable", never a fabricated number;
 *  - migration/schema history comes from migrations-manifest.json (generated by
 *    scripts/gen-migrations-manifest.mjs) and says plainly that per-file remote
 *    applied state is unverified.
 */

export type MigrationEntry = {
  file: string;
  number: number | null;
  title: string;
  description: string;
  tables: string[];
};

export const MIGRATIONS = manifest.migrations as MigrationEntry[];
export const MANIFEST_TABLES: readonly string[] = manifest.tables as string[];
export const MANIFEST_NOTE = manifest.note as string;

export const githubBlobUrl = (file: string) =>
  `https://github.com/Felons88/zapnivo/blob/main/supabase/migrations/${file}`;

/** Tables probed for live row counts on the database overview page. */
export const TABLE_COUNT_TARGETS: readonly { table: string; label: string }[] = [
  { table: "profiles", label: "User/business profiles" },
  { table: "rentals", label: "Rentals" },
  { table: "payments", label: "Payments" },
  { table: "kiosks", label: "Kiosks" },
  // There is no `stations` table — stations are identified by station_id on
  // kiosks/venues; reported honestly as not-a-table rather than queried.
  { table: "system_devices", label: "System devices (control plane)" },
  { table: "error_events", label: "Error events" },
  { table: "app_logs", label: "Application logs" },
  { table: "stripe_events", label: "Stripe webhook events" },
  { table: "inbound_jobs", label: "Inbound email jobs" },
  { table: "email_outbox", label: "Email outbox" },
];

export type TableCount = { table: string; label: string; count: number | null; error?: string };

export type DatabaseHealth = {
  configured: boolean;
  /** true only when a real query succeeded against the backend. */
  reachable: boolean;
  checkedAt: string;
  latencyMs: number | null;
  detail: string;
  counts: TableCount[];
  /** Tables known from the repo manifest — NOT proof they exist remotely. */
  manifestTableCount: number;
  manifestMigrationCount: number;
};

async function headCount(db: SupabaseClient, table: string): Promise<TableCount> {
  const target = TABLE_COUNT_TARGETS.find((t) => t.table === table) ?? { table, label: table };
  try {
    const { count, error } = await db.from(table).select("id", { count: "exact", head: true }).limit(1);
    if (error) return { ...target, count: null, error: error.code ?? error.message };
    return { ...target, count: count ?? 0 };
  } catch (e) {
    return { ...target, count: null, error: e instanceof Error ? e.message.slice(0, 120) : "query failed" };
  }
}

/**
 * Bounded connectivity probe + parallel head counts. `db === null` means the
 * backend isn't configured — reported honestly, never faked.
 */
export async function getDatabaseHealth(db: SupabaseClient | null): Promise<DatabaseHealth> {
  const checkedAt = new Date().toISOString();
  const base = {
    configured: Boolean(db),
    manifestTableCount: MANIFEST_TABLES.length,
    manifestMigrationCount: MIGRATIONS.length,
    checkedAt,
  };
  if (!db) {
    return { ...base, reachable: false, latencyMs: null, detail: "backend not configured (Supabase env vars absent)", counts: [] };
  }

  // Cheap connectivity probe: head count on a control-plane table created in 0042.
  const start = performance.now();
  let reachable = false;
  let detail = "probe failed";
  try {
    const { error } = await db.from("system_feature_flags").select("key", { count: "exact", head: true }).limit(1);
    reachable = !error;
    detail = error ? `probe failed: ${error.code ?? error.message}` : "select ok (system_feature_flags head count)";
  } catch (e) {
    detail = `probe failed: ${e instanceof Error ? e.message.slice(0, 120) : "error"}`;
  }
  const latencyMs = Math.round(performance.now() - start);

  // Counts run even when the probe failed — each reports its own error honestly.
  const settled = await Promise.allSettled(TABLE_COUNT_TARGETS.map((t) => headCount(db, t.table)));
  const counts = settled.map((s) => (s.status === "fulfilled" ? s.value : { table: "?", label: "?", count: null, error: "query threw" }));

  return { ...base, reachable, latencyMs, detail, counts };
}

