export type CatalogRow = { table: string; purpose: string; count: number | null; source: "live" | "catalog only" | "unavailable" };

/** Live counts for the catalog entries marked `live` — bounded, allSettled. */
export async function getCatalogCounts(db: SupabaseClient | null): Promise<Map<string, number | null>> {
  const out = new Map<string, number | null>();
  const liveTables = TABLE_CATALOG.filter((c) => c.live).map((c) => c.table);
  if (!db || liveTables.length === 0) {
    for (const t of liveTables) out.set(t, null);
    return out;
  }
  const settled = await Promise.allSettled(
    liveTables.map(async (t) => {
      const { count, error } = await db.from(t).select("id", { count: "exact", head: true }).limit(1);
      return { t, count: error ? null : (count ?? 0) };
    }),
  );
  for (const s of settled) {
    if (s.status === "fulfilled") out.set(s.value.t, s.value.count);
  }
  // Fill any missing (rejected) entries honestly.
  for (const t of liveTables) if (!out.has(t)) out.set(t, null);
  return out;
}
