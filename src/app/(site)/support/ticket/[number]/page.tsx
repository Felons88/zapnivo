import type { Metadata } from "next";
import { cookies } from "next/headers";
import Link from "next/link";
import { Conversation } from "@/components/Conversation";
import { RequesterReply } from "@/components/RequesterReply";
import { TicketLive } from "@/components/TicketLive";
import { Eyebrow, Section } from "@/components/ui";
import { SESSION_COOKIE } from "@/lib/auth";
import { verifyAccess } from "@/lib/helpdesk/access";
import { defaultCtx, getRequesterThread } from "@/lib/helpdesk/service";

export const dynamic = "force-dynamic";
export const metadata: Metadata = { title: "Your support conversation", robots: { index: false, follow: false } };

const STATE: Record<string, string> = { open: "Received", pending_customer: "Waiting for your reply", pending_internal: "In progress", resolved: "Resolved", closed: "Closed" };

function Gate({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <Section className="pt-40"><div className="mx-auto max-w-xl rounded-2xl bg-white p-8 text-center shadow-sm"><h1 className="display-md">{title}</h1><div className="mt-4 text-graphite">{children}</div><Link href="/support#find-rental" className="mt-6 inline-flex min-h-12 items-center rounded-full bg-lime px-6 font-bold">Track a ticket →</Link></div></Section>
  );
}

export default async function TicketThread({ params, searchParams }: { params: Promise<{ number: string }>; searchParams: Promise<{ t?: string }> }) {
  const { number } = await params;
  const { t } = await searchParams;
  const email = verifyAccess(t, number);
  if (!email) return <Gate title="This link has expired">For your privacy, conversation links are time-limited. Enter your ticket number and email to open it again.</Gate>;
  const ctx = await defaultCtx();
  if (!ctx) return <Gate title="Support isn't available yet">Our support system isn't connected in this environment.</Gate>;
  let thread;
  try { thread = await getRequesterThread(ctx, { kind: "customer", email }, number); } catch { return <Gate title="We couldn't find that ticket">Check the link, or enter your ticket number and email to look it up.</Gate>; }
  const resolved = thread.state === "resolved" || thread.state === "closed";
  const accessToken = (await cookies()).get(SESSION_COOKIE)?.value ?? null;

  return (
    <div className="section-lavender min-h-screen pb-24 pt-36">
      <TicketLive ticketId={thread.id} intervalMs={15000} accessToken={accessToken} />
      <div className="container-z mx-auto max-w-3xl">
        <Link href="/support" className="text-sm font-bold underline underline-offset-4">← Help center</Link>
        <div className="mt-5 flex flex-wrap items-start justify-between gap-3">
          <div><Eyebrow className="text-forest">Ticket {thread.number}</Eyebrow><h1 className="display-md mt-3">{thread.category}</h1></div>
          <span className="rounded-full bg-lime px-3 py-1 text-xs font-extrabold uppercase tracking-wider">{STATE[thread.state] ?? thread.state}</span>
        </div>
        <p className="mt-3 text-sm text-graphite">{thread.withPerson ? "A Zapnivo team member is handling this. We'll reply by email and here." : "Our assistant is helping with this. You can ask for a person at any time."}</p>
        <div className="mt-8"><Conversation messages={thread.messages} /></div>
        <div className="mt-8"><RequesterReply number={thread.number} token={t} mode="customer" withPerson={thread.withPerson} resolved={resolved} /></div>
        <p className="mt-6 text-xs leading-5 text-graphite/80">Replies from Zapnivo's assistant are generated by AI and may contain mistakes. Only a team member can approve refunds. Never share card numbers or passwords.</p>
      </div>
    </div>
  );
}
