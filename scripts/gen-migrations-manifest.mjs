#!/usr/bin/env node
/**
 * Generates src/lib/system/migrations-manifest.json from supabase/migrations/*.sql.
 *
 * Extracts, per migration file (sorted by filename = apply order):
 *   - file name + numeric prefix
 *   - title/description from the leading `--` comment header
 *   - the tables it creates (regex over `create table` statements)
 *
 * This manifest is the ONLY source the /system/database pages use for schema
 * history — the DB itself does not track which files were applied, so the UI
 * must label remote state as unverified. Run: node scripts/gen-migrations-manifest.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "supabase", "migrations");
const outPath = join(root, "src", "lib", "system", "migrations-manifest.json");

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const CREATE_TABLE = /create\s+table\s+(?:if\s+not\s+exists\s+)?(?:public\.)?([a-zA-Z_][a-zA-Z0-9_]*)/gi;

const migrations = [];
const tables = [];
const seenTables = new Set();

for (const file of files) {
  const sql = readFileSync(join(migrationsDir, file), "utf8");
  const lines = sql.split(/\r?\n/);

  // Leading comment header: consecutive `--` lines from the top of the file.
  const header = [];
  for (const line of lines) {
    const t = line.trim();
    if (t.startsWith("--")) header.push(t.replace(/^--\s?/, "").trim());
    else if (t === "" && header.length === 0) continue; // leading blanks
    else break;
  }
  const title = header[0] ?? file.replace(/\.sql$/, "").replace(/_/g, " ");
  const description = header.slice(1).join(" ").slice(0, 400);

  const fileTables = [];
  for (const m of sql.matchAll(CREATE_TABLE)) {
    const t = m[1].toLowerCase();
    fileTables.push(t);
    if (!seenTables.has(t)) { seenTables.add(t); tables.push(t); }
  }

  migrations.push({
    file,
    number: parseInt(file.split("_")[0], 10) || null,
    title,
    description,
    tables: [...new Set(fileTables)],
  });
}

const manifest = {
  generatedFrom: "supabase/migrations",
  note: "Generated by scripts/gen-migrations-manifest.mjs — do not edit by hand. Files in repo order; remote applied-state is NOT tracked per file.",
  migrationCount: migrations.length,
  tableCount: tables.length,
  migrations,
  tables,
};

writeFileSync(outPath, JSON.stringify(manifest, null, 2) + "\n");
console.log(`wrote ${outPath}: ${migrations.length} migrations, ${tables.length} tables`);
